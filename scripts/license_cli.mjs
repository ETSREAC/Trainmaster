#!/usr/bin/env node
/**
 * TrainMaster - Supporter Key Generator & Verifier (ECDSA P-256)
 * =============================================================================
 * Generiert kryptografisch signierte Freischaltcodes für Buy-Me-a-Coffee Supporter.
 * 
 * Der private Schlüssel liegt NUR LOKAL in 'scripts/.secret_license_keys.json'
 * und wird NIEMALS auf GitHub hochgeladen (in .gitignore geschützt).
 * 
 * Der öffentliche Schlüssel liegt in 'client/src/licensePublicKey.ts'.
 * 
 * Benutzung:
 *   node scripts/license_cli.mjs "Name oder E-Mail des Unterstützers"
 *   npm run license:gen "Erik"
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import crypto from 'crypto';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const SECRET_KEY_FILE = path.join(__dirname, '.secret_license_keys.json');
const CLIENT_PUB_KEY_FILE = path.join(__dirname, '..', 'client', 'src', 'licensePublicKey.ts');

const { subtle } = crypto.webcrypto;

function base64urlEncode(buf) {
  return Buffer.from(buf).toString('base64')
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
}

function base64urlDecode(str) {
  str = str.replace(/-/g, '+').replace(/_/g, '/');
  while (str.length % 4) str += '=';
  return Buffer.from(str, 'base64');
}

async function ensureKeys() {
  if (fs.existsSync(SECRET_KEY_FILE)) {
    const raw = fs.readFileSync(SECRET_KEY_FILE, 'utf-8');
    return JSON.parse(raw);
  }

  console.log('🔑 Erzeuge neues ECDSA P-256 Schlüsselpaar für TrainMaster Supporter-Codes...');
  const keyPair = await subtle.generateKey(
    { name: 'ECDSA', namedCurve: 'P-256' },
    true,
    ['sign', 'verify']
  );

  const privateKeyJwk = await subtle.exportKey('jwk', keyPair.privateKey);
  const publicKeySpki = await subtle.exportKey('spki', keyPair.publicKey);
  const publicKeySpkiBase64 = Buffer.from(publicKeySpki).toString('base64');

  const keysData = {
    createdAt: new Date().toISOString(),
    privateKeyJwk,
    publicKeySpkiBase64
  };

  fs.writeFileSync(SECRET_KEY_FILE, JSON.stringify(keysData, null, 2), 'utf-8');

  // Schreibe Public Key in Client-Quellcode
  const clientContent = `// Auto-generated by scripts/license_cli.mjs
// This public key is safe for open-source repositories.
// Only the matching private key on the creator's machine can generate valid supporter signatures.
export const SUPPORTER_PUBLIC_KEY_SPKI = '${publicKeySpkiBase64}';
`;
  fs.writeFileSync(CLIENT_PUB_KEY_FILE, clientContent, 'utf-8');
  console.log(`✅ Schlüsselpaar erzeugt!\n   Privater Schlüssel: ${SECRET_KEY_FILE}\n   Öffentlicher Schlüssel: ${CLIENT_PUB_KEY_FILE}`);

  return keysData;
}

async function generateCode(supporterName) {
  const name = supporterName.trim();
  if (!name) {
    console.error('❌ Fehler: Bitte einen Namen oder eine E-Mail angeben!');
    process.exit(1);
  }

  const keys = await ensureKeys();
  const privateKey = await subtle.importKey(
    'jwk',
    keys.privateKeyJwk,
    { name: 'ECDSA', namedCurve: 'P-256' },
    false,
    ['sign']
  );

  const payload = JSON.stringify({
    supporter: name,
    tier: 'Clean Edition 25EUR+',
    issuedAt: new Date().toISOString().split('T')[0]
  });

  const payloadBytes = new TextEncoder().encode(payload);
  const signature = await subtle.sign(
    { name: 'ECDSA', hash: { name: 'SHA-256' } },
    privateKey,
    payloadBytes
  );

  const partPayload = base64urlEncode(payloadBytes);
  const partSig = base64urlEncode(signature);
  const fullCode = `TM1.${partPayload}.${partSig}`;

  console.log('\n============================================================');
  console.log(`🎉 SUPPORTER-CODE FÜR: ${name}`);
  console.log('============================================================');
  console.log(`\n${fullCode}\n`);
  console.log('============================================================');
  console.log('Diesen Code dem Spender senden (z. B. als Dankeschön auf BMC).');
  console.log('Der Spender gibt den Code in TrainMaster ein und schaltet die Clean-Version frei!\n');

  return fullCode;
}

async function verifyCode(codeStr) {
  const parts = codeStr.trim().split('.');
  if (parts.length !== 3 || parts[0] !== 'TM1') {
    console.error('❌ Ungültiges Code-Format (muss mit TM1. beginnen)');
    return false;
  }

  const keys = await ensureKeys();
  const publicKey = await subtle.importKey(
    'spki',
    Buffer.from(keys.publicKeySpkiBase64, 'base64'),
    { name: 'ECDSA', namedCurve: 'P-256' },
    false,
    ['verify']
  );

  const payloadBytes = base64urlDecode(parts[1]);
  const sigBytes = base64urlDecode(parts[2]);

  const isValid = await subtle.verify(
    { name: 'ECDSA', hash: { name: 'SHA-256' } },
    publicKey,
    sigBytes,
    payloadBytes
  );

  if (isValid) {
    const payload = JSON.parse(new TextDecoder().decode(payloadBytes));
    console.log('✅ CODE IST GÜLTIG!', payload);
    return true;
  } else {
    console.log('❌ UNGÜLTIGE SIGNATUR!');
    return false;
  }
}

async function main() {
  const args = process.argv.slice(2);
  if (args.length === 0) {
    console.log('Verwendung:');
    console.log('  node scripts/license_cli.mjs "Name des Spenders"');
    console.log('  node scripts/license_cli.mjs --verify "TM1.xxx.yyy"');
    process.exit(0);
  }

  if (args[0] === '--verify') {
    await verifyCode(args[1]);
  } else {
    await generateCode(args[0]);
  }
}

main().catch(err => {
  console.error('Fehler:', err);
  process.exit(1);
});
